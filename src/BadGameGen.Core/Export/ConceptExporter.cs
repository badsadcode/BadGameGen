using System.Text;
using System.Text.Json;
using BadGameGen.Core.Generation;

namespace BadGameGen.Core.Export;

public enum ExportFormat { Markdown, Text, Json }

/// <summary>Turns a concept (optionally with vault notes) into shareable text.</summary>
public static class ConceptExporter
{
    public static string Export(Concept c, ExportFormat format, string? notes = null, string? titleOverride = null) => format switch
    {
        ExportFormat.Markdown => Markdown(c, notes, titleOverride),
        ExportFormat.Text => PlainText(c, notes, titleOverride),
        ExportFormat.Json => JsonSerializer.Serialize(new { concept = c, notes }, Vault.VaultStore.JsonOptions),
        _ => throw new ArgumentOutOfRangeException(nameof(format)),
    };

    public static string FileName(Concept c, ExportFormat format, string? titleOverride = null)
    {
        var name = new string((titleOverride ?? c.Title).Select(ch => char.IsLetterOrDigit(ch) ? ch : '-').ToArray()).Trim('-');
        while (name.Contains("--")) name = name.Replace("--", "-");
        if (name.Length == 0) name = c.Codename;
        return name + format switch { ExportFormat.Markdown => ".md", ExportFormat.Text => ".txt", _ => ".json" };
    }

    private static IEnumerable<CreepProposal> KeptCreep(Concept c) =>
        c.Creep.Where(x => x.Status != CreepStatus.Rejected);

    public static string Markdown(Concept c, string? notes = null, string? titleOverride = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# {titleOverride ?? c.Title}");
        sb.AppendLine();
        sb.AppendLine($"*{c.Hook}*");
        sb.AppendLine();
        if (c.Chips.Count > 0) sb.AppendLine(string.Join(" · ", c.Chips.Select(x => $"`{x.Label}`"))).AppendLine();
        sb.AppendLine(c.Pitch);
        sb.AppendLine();
        if (!string.IsNullOrWhiteSpace(c.BadIdea))
        {
            sb.AppendLine("## Why it's a bad idea (and why it might work)");
            sb.AppendLine();
            sb.AppendLine($"- **Bad idea:** {c.BadIdea}");
            sb.AppendLine($"- **Might work:** {c.MightWork}");
            sb.AppendLine();
        }
        if (c.Expanded.Count > 0)
        {
            sb.AppendLine("## Concept details");
            sb.AppendLine();
            foreach (var s in c.Expanded)
            {
                var body = s.Body.Contains('\n')
                    ? "\n" + string.Join("\n", s.Body.Split('\n').Select(l => $"  - {l}"))
                    : " " + s.Body;
                sb.AppendLine($"- **{s.Heading}:**{body}");
            }
            sb.AppendLine();
        }
        var creep = KeptCreep(c).ToList();
        if (creep.Count > 0)
        {
            sb.AppendLine("## Feature Creep 😈");
            sb.AppendLine();
            sb.AppendLine("*Just one more system...*");
            sb.AppendLine();
            foreach (var x in creep)
            {
                var status = x.Status == CreepStatus.Accepted ? "✅" : "❔";
                sb.AppendLine($"- {status} **{x.Name}** ({x.KindLabel}, complexity {x.Complexity}): {x.Pitch}{(x.Connects != null ? " " + x.Connects : "")}");
            }
            if (c.CreepMeter != null)
            {
                sb.AppendLine();
                sb.AppendLine($"**Creep meter:** {c.CreepMeter.Score}% ({c.CreepMeter.Label}){(c.CreepMeter.Warning != null ? $". {c.CreepMeter.Warning}" : "")}");
            }
            sb.AppendLine();
        }
        if (!string.IsNullOrWhiteSpace(notes))
        {
            sb.AppendLine("## Notes");
            sb.AppendLine();
            sb.AppendLine(notes.Trim());
            sb.AppendLine();
        }
        sb.AppendLine("---");
        sb.AppendLine($"`{c.Codename}` · seed `{c.Recipe.Seed}` · chaos {Math.Round(c.Recipe.Chaos * 100)}% · scope {c.ScopeName} · packs {string.Join(", ", c.Library.Select(p => $"{p.Id}@{p.Version}"))}");
        sb.AppendLine();
        sb.AppendLine("*Generated by BadGameGen, Bad Ideas Works. Terrible ideas. Surprisingly playable games.*");
        return sb.ToString();
    }

    public static string PlainText(Concept c, string? notes = null, string? titleOverride = null)
    {
        var sb = new StringBuilder();
        var title = (titleOverride ?? c.Title).ToUpperInvariant();
        sb.AppendLine(title);
        sb.AppendLine(new string('=', title.Length));
        sb.AppendLine(c.Hook);
        sb.AppendLine();
        sb.AppendLine(c.Pitch);
        sb.AppendLine();
        if (!string.IsNullOrWhiteSpace(c.BadIdea))
        {
            sb.AppendLine($"Why it's a bad idea: {c.BadIdea}");
            sb.AppendLine($"Why it might work: {c.MightWork}");
            sb.AppendLine();
        }
        foreach (var s in c.Expanded)
            sb.AppendLine($"{s.Heading}: {s.Body.Replace("\n", " ")}");
        var creep = KeptCreep(c).ToList();
        if (creep.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("FEATURE CREEP (just one more system...)");
            foreach (var x in creep)
                sb.AppendLine($"* {x.Name} [{x.KindLabel}{(x.Status == CreepStatus.Accepted ? ", accepted" : "")}]: {x.Pitch}{(x.Connects != null ? " " + x.Connects : "")}");
            if (c.CreepMeter != null) sb.AppendLine($"Creep meter: {c.CreepMeter.Score}% ({c.CreepMeter.Label})");
        }
        if (!string.IsNullOrWhiteSpace(notes))
        {
            sb.AppendLine();
            sb.AppendLine("NOTES");
            sb.AppendLine(notes.Trim());
        }
        sb.AppendLine();
        sb.AppendLine($"{c.Codename} | seed {c.Recipe.Seed} | {c.ScopeName}");
        return sb.ToString();
    }
}
